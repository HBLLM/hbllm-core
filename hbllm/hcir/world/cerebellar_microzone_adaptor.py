"""Cerebellar Forward Dynamics & Microzone Granule-Purkinje Motor Error Adaptation.

Biologically grounded in Marr-Albus-Ito cerebellar cortex microzone theory
(Marr, 1969; Albus, 1971; Ito, 1982):
1. Granule Cell High-Dimensional Sparse Expansion:
   - Mossy fibers convey low-dimensional kinematic state and motor efference copies.
   - Granule cells project inputs into a high-dimensional sparse representation
     (D_granule = 128) using deterministic orthogonal random projection and top-k
     winner-take-all sparsity.
2. Purkinje Cell Forward Model Readout:
   - Parallel fiber synapses on Purkinje cells linearly decode the high-dimensional
     granule cell pattern to predict rapid motor outcomes (displacement, latency).
3. Climbing Fiber Error Signaling & Long-Term Depression (LTD):
   - Inferior olive climbing fibers convey sensorimotor prediction discrepancies
     delta = outcome_actual - outcome_predicted.
   - Co-activation of climbing fibers and parallel fibers triggers heterosynaptic
     LTD, depressing active synaptic weights:
     Delta W_pf = -eta_ltd * x_gc * delta.
   - Delivers sub-millisecond feedforward motor recalibration without trial-and-error latency.
"""

from __future__ import annotations

import logging
import math
from dataclasses import dataclass
from typing import Any

import numpy as np

from hbllm.hcir.world.causal_discovery import CausalPredicate

logger = logging.getLogger(__name__)


@dataclass
class MotorPrediction:
    """Feedforward prediction generated by cerebellar microzone Purkinje cells."""

    predicted_displacement: tuple[float, float]
    predicted_latency_ms: float
    confidence: float
    active_granule_count: int


@dataclass
class ClimbingFiberFeedback:
    """Sensorimotor error feedback conveyed by climbing fibers for cerebellar LTD."""

    action_id: Any
    actual_displacement: tuple[float, float]
    predicted_displacement: tuple[float, float]
    error_vector: tuple[float, float]
    error_magnitude: float
    weights_depressed_count: int
    timestamp: float

    def to_causal_predicate(self) -> CausalPredicate:
        """Export climbing fiber error feedback as a declarative HCIR CausalPredicate."""
        return CausalPredicate(
            variable="cerebellar_climbing_error",
            operator="==",
            value=f"err:{self.error_magnitude:.2f}:act:{self.action_id}",
            relation="cerebellar_microzone_ltd",
            target_entity="cerebellar_purkinje",
        )


class CerebellarMicrozoneAdaptor:
    """Cerebellar microzone motor forward model with granule expansion and LTD adaptation."""

    def __init__(
        self,
        granule_dimension: int = 128,
        top_k_active_granules: int = 16,
        learning_rate_ltd: float = 0.05,
    ) -> None:
        """Initialize cerebellar microzone adaptor.

        Args:
            granule_dimension: Number of sparse granule cells in the microzone layer.
            top_k_active_granules: Number of active winning granule cells per step.
            learning_rate_ltd: Learning rate for parallel fiber synaptic depression.
        """
        self.granule_dim = max(32, int(granule_dimension))
        self.top_k = max(4, min(self.granule_dim // 2, int(top_k_active_granules)))
        self.learning_rate = max(0.001, float(learning_rate_ltd))

        # Input projection matrix: maps (dr, dc, speed, action_idx) into granule space
        rng = np.random.RandomState(42)
        self._projection_weights = rng.randn(self.granule_dim, 6)
        self._projection_bias = rng.randn(self.granule_dim) * 0.1

        # Purkinje readout weights for each action: action_id -> (W_r, W_c, W_lat) of shape (granule_dim,)
        self._purkinje_weights: dict[Any, np.ndarray] = {}
        self.total_adaptations: int = 0

    def _encode_mossy_fibers(
        self,
        action_id: Any,
        current_state: dict[str, Any],
    ) -> np.ndarray:
        """Convert state and motor efference copy into low-dimensional mossy fiber vector."""
        r = float(current_state.get("r", 0.0))
        c = float(current_state.get("c", 0.0))
        vr = float(current_state.get("vr", 0.0))
        vc = float(current_state.get("vc", 0.0))
        speed = math.sqrt(vr * vr + vc * vc)

        try:
            act_num = float(int(action_id))
        except (ValueError, TypeError):
            act_num = float(abs(hash(str(action_id))) % 8)

        # 6-D input vector
        return np.array([r * 0.1, c * 0.1, vr, vc, speed, act_num * 0.2], dtype=np.float64)

    def _expand_granule_cells(self, mossy_input: np.ndarray) -> np.ndarray:
        """Perform sparse high-dimensional granule cell expansion with top-k WTA."""
        activations = np.dot(self._projection_weights, mossy_input) + self._projection_bias
        # Top-k winner-take-all sparsity
        sparse_gc = np.zeros(self.granule_dim, dtype=np.float64)
        top_indices = np.argsort(activations)[-self.top_k :]
        sparse_gc[top_indices] = np.maximum(0.0, activations[top_indices])
        norm = np.linalg.norm(sparse_gc)
        if norm > 0:
            sparse_gc /= norm
        return sparse_gc

    def _get_or_init_weights(self, action_id: Any) -> np.ndarray:
        """Retrieve or initialize 3x(granule_dim) Purkinje weights for an action."""
        if action_id not in self._purkinje_weights:
            # Row 0: dr, Row 1: dc, Row 2: latency_ms
            w = np.zeros((3, self.granule_dim), dtype=np.float64)
            # Default directional heuristic based on action integer if cardinal
            try:
                act = int(action_id)
                if act == 0:  # UP
                    w[0, :] = -1.0 / self.top_k
                elif act == 1:  # DOWN
                    w[0, :] = 1.0 / self.top_k
                elif act == 2:  # LEFT
                    w[1, :] = -1.0 / self.top_k
                elif act == 3:  # RIGHT
                    w[1, :] = 1.0 / self.top_k
            except (ValueError, TypeError):
                pass
            w[2, :] = 10.0 / self.top_k  # Baseline 10 ms
            self._purkinje_weights[action_id] = w
        return self._purkinje_weights[action_id]

    def predict_outcome(
        self,
        action_id: Any,
        current_state: dict[str, Any],
    ) -> MotorPrediction:
        """Predict feedforward kinematic outcome via Purkinje cell readout."""
        mossy = self._encode_mossy_fibers(action_id, current_state)
        gc = self._expand_granule_cells(mossy)
        w = self._get_or_init_weights(action_id)

        # Output = W * gc
        pred = np.dot(w, gc)
        dr = float(pred[0])
        dc = float(pred[1])
        lat = max(1.0, float(pred[2]))

        active_count = int(np.count_nonzero(gc))
        confidence = float(np.clip(1.0 - 0.05 * abs(dr * dc), 0.2, 1.0))

        return MotorPrediction(
            predicted_displacement=(dr, dc),
            predicted_latency_ms=lat,
            confidence=confidence,
            active_granule_count=active_count,
        )

    def adapt_from_feedback(
        self,
        action_id: Any,
        current_state: dict[str, Any],
        actual_displacement: tuple[float, float],
        actual_latency_ms: float = 10.0,
        timestamp: float = 0.0,
    ) -> ClimbingFiberFeedback:
        """Apply heterosynaptic LTD to parallel-fiber Purkinje weights from climbing error."""
        mossy = self._encode_mossy_fibers(action_id, current_state)
        gc = self._expand_granule_cells(mossy)
        w = self._get_or_init_weights(action_id)

        pred = np.dot(w, gc)
        err_r = actual_displacement[0] - float(pred[0])
        err_c = actual_displacement[1] - float(pred[1])
        err_lat = actual_latency_ms - float(pred[2])
        err_vec = np.array([err_r, err_c, err_lat], dtype=np.float64)

        err_mag = float(math.sqrt(err_r * err_r + err_c * err_c))

        # Cerebellar LTD weight adaptation: Delta W = eta * outer(error, gc)
        delta_w = self.learning_rate * np.outer(err_vec, gc)
        w += delta_w
        self._purkinje_weights[action_id] = w
        self.total_adaptations += 1

        active_indices = np.where(gc > 0)[0]

        return ClimbingFiberFeedback(
            action_id=action_id,
            actual_displacement=actual_displacement,
            predicted_displacement=(float(pred[0]), float(pred[1])),
            error_vector=(err_r, err_c),
            error_magnitude=err_mag,
            weights_depressed_count=len(active_indices),
            timestamp=timestamp,
        )

    def reset(self) -> None:
        """Reset learned Purkinje weights and adaptation history."""
        self._purkinje_weights.clear()
        self.total_adaptations = 0
